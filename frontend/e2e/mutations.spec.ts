test('roles: create, edit with unsaved-changes prompt, delete', async ({ page, context }) => {
  await signInAs(context, 'admin')
  await page.goto('/roles')
  await page.getByTestId('role-new').click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Name').fill('reviewer-e2e')
  await dialog.getByLabel('section.courses').check()
  await dialog.getByTestId('dialog-submit').click()
  await expect(page.getByText('Role created.')).toBeVisible()
  const row = page.getByRole('row').filter({ hasText: 'reviewer-e2e' })
  await expect(row).toContainText('1 permissions')
  await row.getByRole('button', { name: 'Edit' }).click()
  await dialog.getByLabel('section.sources').check()
  await dialog.getByRole('button', { name: 'Cancel' }).click()
  await expect(dialog.getByTestId('discard-bar')).toBeVisible()
  await dialog.getByRole('button', { name: 'Keep editing' }).click()
  await dialog.getByTestId('dialog-submit').click()
  await expect(page.getByText('Role saved.')).toBeVisible()
  await expect(row).toContainText('2 permissions')
  await row.getByRole('button', { name: 'Delete' }).click()
  await expect(dialog).toContainText('reviewer-e2e')
  await dialog.getByTestId('dialog-submit').click()
  await expect(page.getByText('Role deleted.')).toBeVisible()
  await expect(row).toHaveCount(0)
})

test('every enabled action button opens a dialog and can be cancelled', async ({ page, context }) => {
  await signInAs(context, 'admin')
  await page.goto('/users')
  const row = page.getByRole('row').filter({ hasText: sessions().student.email })
  for (const name of ['Assign role', 'Ban', 'Delete']) {
    await row.getByRole('button', { name, exact: true }).click()
    await expect(page.getByRole('dialog')).toBeVisible()
    await page.getByRole('dialog').getByRole('button', { name: 'Cancel' }).click()
    await expect(page.getByRole('dialog')).toBeHidden()
  }
})

test('invites: create shows the link once, accept works for another account, revoke marks it', async ({ page, context, browser }) => {
  await signInAs(context, 'admin')
  await page.goto('/invites')
  await expect(page.getByText('The backend does not list earlier invites yet.', { exact: false })).toBeVisible()
  await expect(page.getByTestId('invite-create')).toBeDisabled()
  await page.getByLabel('Course tags').fill('e2e-course')
  await page.getByTestId('invite-create').click()
  const item = page.getByTestId('invite-item').first()
  await expect(item).toBeVisible()
  const link = (await item.getByTestId('invite-link').innerText()).trim()
  expect(link).toMatch(/\/invite\/[0-9a-f-]{36}$/)
  const other = await browser.newContext()
  await signInAs(other, 'inviteme')
  const guest = await other.newPage()
  await guest.goto(link)
  await expect(guest.getByTestId('invite-open')).toBeVisible()
  await expect(guest.getByText('You now have access to: e2e-course')).toBeVisible()
  await other.close()
  await item.getByRole('button', { name: 'Revoke' }).click()
  await expect(page.getByText('Invite revoked.')).toBeVisible()
  await expect(item.getByText('Revoked')).toBeVisible()
})
