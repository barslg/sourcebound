import { expect, recordApi, sessions, signInAs, test } from './fixtures'

test('assigning a role shows aria-busy, then a toast, then refetches the list', async ({ page, context }) => {
  await signInAs(context, 'admin')
  const calls = recordApi(page)
  await page.route('**/api/v1/roles/student/assign', async (route) => {
    await new Promise((r) => setTimeout(r, 800))
    await route.continue()
  })
  await page.goto('/users')
  const row = page.getByRole('row').filter({ hasText: sessions().assignee.email })
  await row.getByRole('button', { name: 'Assign role' }).click()
  const dialog = page.getByRole('dialog')
  await dialog.locator('#assign-role').click()
  await page.getByRole('option', { name: 'student' }).click()
  const submit = dialog.getByTestId('dialog-submit')
  await submit.click()
  await expect(submit).toHaveAttribute('aria-busy', 'true')
  await expect(page.getByText('Role assigned.')).toBeVisible()
  await expect(dialog).toBeHidden()
  const posted = calls.findIndex((c) => c.method === 'POST' && c.path === '/api/v1/roles/student/assign')
  expect(posted).toBeGreaterThan(-1)
  expect(calls.slice(posted + 1).some((c) => c.method === 'GET' && c.path === '/api/v1/users')).toBe(true)
})

