test('plan page: a topic opens inline to its blocks, rename autosaves on blur, move and delete go through the row menu', async ({ page, context }) => {
  await signInAs(context, 'admin')
  await page.goto(`/courses/${ids().editing}/plan`)
  await page.getByTestId('question').getByLabel('Who is the learner at the start?').fill('Anyone')
  await page.getByTestId('question').getByRole('button', { name: 'Save answer' }).click()
  await expect(page.getByTestId('save-status')).toContainText('Saved just now')
  const outline = page.getByTestId('plan-outline')
  await expect(outline).toContainText('Foundations')
  const topic = page.getByTestId('plan-topic').filter({ hasText: SEED_TOPIC })
  await topic.getByTestId('topic-toggle').click()
  await expect(page.getByTestId('plan-block')).toHaveCount(2)
  await expect(page.getByTestId('plan-block').first()).toContainText('Teaches')
  await expect(page.getByTestId('plan-block').first()).toContainText('P1')
  await topic.getByTestId('topic-title').fill('Basics renamed')
  await page.keyboard.press('Tab')
  await expect(page.getByTestId('save-status')).toContainText('Saved just now')
  await expect(outline).toContainText('Basics renamed')
  const renamed = page.getByTestId('plan-topic').filter({ hasText: 'Basics renamed' })
  await renamed.getByRole('button', { name: 'More actions for Basics renamed' }).click()
  await page.getByRole('menuitem', { name: 'Move down' }).click()
  await expect(page.getByTestId('save-status')).toContainText('Saved just now')
  const afterMove = await (await page.request.get(`/api/v1/courses/${ids().editing}/plan`)).json() as { modules: Array<{ topics: Array<{ title: string }> }> }
  expect(afterMove.modules[0]?.topics.map((x) => x.title)).toEqual(['Terms', 'Basics renamed'])
  await renamed.getByRole('button', { name: 'More actions for Basics renamed' }).click()
  await page.getByRole('menuitem', { name: 'Delete from plan' }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog).toContainText('Basics renamed')
  await expect(dialog).toContainText('cannot be undone')
  await dialog.locator('#confirm-typed').fill('Basics renamed')
  await dialog.getByTestId('dialog-submit').click()
  await expect(page.getByTestId('save-status')).toContainText('Saved just now')
  await expect(outline).not.toContainText('Basics renamed')
  const afterDelete = await (await page.request.get(`/api/v1/courses/${ids().editing}/plan`)).json() as { modules: Array<{ topics: Array<{ title: string }> }> }
  expect(afterDelete.modules[0]?.topics.map((x) => x.title)).toEqual(['Terms'])
})

