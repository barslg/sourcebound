test('plan editor: a change by someone else gives 409 with Reload theirs and Keep mine', async ({ page, context }) => {
  await signInAs(context, 'admin')
  const { conflict } = ids()
  await page.goto(`/courses/${conflict}/plan`)
  const tree = page.getByTestId('plan-tree')
  await tree.locator('.p-tree-node-label', { hasText: /^Foundations$/ }).click()
  await page.getByLabel('Title', { exact: true }).fill('Foundations by me')
  await page.getByTestId('plan-rename').click()
  await expect(page.getByTestId('unsaved')).toBeVisible()
  const plan = await (await page.request.get(`/api/v1/courses/${conflict}/plan`)).json() as { modules: Array<{ id: string }> }
  const rival = await page.request.patch(`/api/v1/courses/${conflict}/plan`, {
    headers: { 'X-CSRF-Token': sessions().admin.csrf },
    data: { operations: [{ op: 'rename_module', id: plan.modules[1]?.id, title: 'Practice by someone else' }] },
  })
  expect(rival.status()).toBe(200)
  await page.getByTestId('plan-save').click()
  await expect(page.getByTestId('conflict')).toContainText('Someone changed this plan')
  await expect(page.getByTestId('unsaved')).toBeVisible()
  await page.getByTestId('reload-theirs').click()
  await expect(page.getByTestId('conflict')).toHaveCount(0)
  await expect(page.getByTestId('unsaved')).toHaveCount(0)
  await expect(tree).toContainText('Practice by someone else')
  await expect(tree).not.toContainText('Foundations by me')
  await page.getByLabel('Title', { exact: true }).fill('Foundations by me')
  await page.getByTestId('plan-rename').click()
  await page.request.patch(`/api/v1/courses/${conflict}/plan`, {
    headers: { 'X-CSRF-Token': sessions().admin.csrf },
    data: { operations: [{ op: 'rename_module', id: plan.modules[1]?.id, title: 'Practice again' }] },
  })
  await page.getByTestId('plan-save').click()
  await expect(page.getByTestId('conflict')).toBeVisible()
  await page.getByTestId('keep-mine').click()
  await expect(page.getByText('Plan saved.')).toBeVisible()
  await expect(tree).toContainText('Foundations by me')
  await expect(tree).toContainText('Practice again')
})

test('plan editor: dragging a topic in the tree reorders it, stays unsaved until saved, then persists', async ({ page, context }) => {
  await signInAs(context, 'admin')
  const { dnd } = ids()
  await page.goto(`/courses/${dnd}/plan`)
  const tree = page.getByTestId('plan-tree')
  await tree.getByRole('treeitem', { name: 'Foundations' }).locator('.p-tree-node-toggle-button').click()
  const order = async (): Promise<string[]> => (await tree.locator('.p-tree-node-label').allInnerTexts()).map((t) => t.trim())
  expect(await order()).toEqual(['Foundations', 'Basics', 'Terms', 'Practice'])
  await tree.locator('.p-tree-node-content', { hasText: /^Terms$/ }).dragTo(tree.locator('.p-tree-node-content', { hasText: /^Basics$/ }))
  await expect(page.getByTestId('unsaved')).toBeVisible()
  expect(await order()).toEqual(['Foundations', 'Terms', 'Basics', 'Practice'])
  await page.getByTestId('plan-save').click()
  await expect(page.getByText('Plan saved.')).toBeVisible()
  await expect(page.getByTestId('unsaved')).toHaveCount(0)
  const saved = await (await page.request.get(`/api/v1/courses/${dnd}/plan`)).json() as { modules: Array<{ topics: Array<{ title: string }> }> }
  expect(saved.modules[0]?.topics.map((t) => t.title)).toEqual(['Terms', 'Basics'])
})
