import { expect, ids, recordApi, signInAs, test } from './fixtures'

const SEED_TOPIC = 'Basics'

test('my courses: the backend error is shown while the list route is missing, and creating is a busy, toasted request', async ({ page, context }) => {
  await signInAs(context, 'admin')
  const calls = recordApi(page)
  await page.route('**/api/v1/courses', async (route) => {
    if (route.request().method() === 'POST') await new Promise((r) => setTimeout(r, 700))
    await route.continue()
  })
  await page.goto('/courses')
  const box = page.locator('[data-view="error"]')
  await expect(box).toBeVisible()
  await expect(box).toContainText('Method Not Allowed')
  await page.getByTestId('course-new').click()
  const dialog = page.getByRole('dialog')
  await expect(dialog.getByTestId('dialog-submit')).toBeDisabled()
  await dialog.getByLabel('Title').fill('Created from e2e')
  const submit = dialog.getByTestId('dialog-submit')
  await submit.click()
  await expect(submit).toHaveAttribute('aria-busy', 'true')
  await expect(page.getByText('Course created.')).toBeVisible()
  await expect(page).toHaveURL(/\/courses\/[0-9a-f-]{36}\/plan$/)
  await expect(page.getByTestId('course-head')).toContainText('Created from e2e')
  await expect(page.getByTestId('needs-now')).toContainText('set the course profile')
  const post = calls.find((c) => c.method === 'POST' && c.path === '/api/v1/courses')
  expect(post?.csrf).toBeTruthy()
})

