"""Write the client permission codes from the backend (single source of truth).

Output: frontend/src/api/permissions.generated.ts with
- PERMISSION_CODES: every code of the RBAC catalogue;
- ROUTE_CODES: "METHOD /api/v1/path" -> the codes the backend requires for it
  (the same inventory scripts/check_routes.py prints).

Usage: python scripts/export_permissions.py          write the file
       python scripts/export_permissions.py --check  exit 1 when the file is stale
The caller is the frontend unit gate t04i-permissions and the gates test.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO / "src"))
sys.path.insert(0, str(REPO / "scripts"))

TARGET = REPO / "frontend" / "src" / "api" / "permissions.generated.ts"


def render() -> str:
    """The generated TypeScript module text."""
    import check_routes

    from app.main import create_app
    from app.rbac.catalogue import codes

    app = create_app(sync_on_startup=False)
    route_codes: dict[str, list[str]] = {}
    for row in check_routes.inventory(app, REPO / "src"):
        head, _, tail = row.partition("  codes=")
        method, path = head.split("  ctx=")[0].split(None, 1)
        value = tail.strip()
        route_codes[f"{method} {path.strip()}"] = (
            [] if value.startswith(("exempt", "self", "NONE")) else value.split(",")
        )
    lines = [
        "// Generated by scripts/export_permissions.py - do not edit.",
        f"export const PERMISSION_CODES: readonly string[] = {json.dumps(sorted(codes()))}",
        "export const ROUTE_CODES: Readonly<Record<string, readonly string[]>> = {",
    ]
    lines += [f"  {json.dumps(k)}: {json.dumps(v)}," for k, v in sorted(route_codes.items())]
    lines.append("}")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    """Write or check the generated file."""
    text = render()
    if "--check" in argv:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != text:
            print("permissions.generated.ts is stale: run scripts/export_permissions.py")
            return 1
        return 0
    TARGET.write_text(text, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
